create extension if not exists pgcrypto;

create table public.kamu_inventory_users (
 id uuid primary key default gen_random_uuid(),
 username text not null unique,
 password_hash text not null,
 password_salt text not null,
 is_active boolean not null default true,
 created_at timestamptz not null default now(),
 last_login_at timestamptz
);
create unique index kamu_inventory_users_username_lower_uq on public.kamu_inventory_users(lower(username));

create or replace function public.kamu_inventory_enforce_user_limit()
returns trigger language plpgsql set search_path to 'public' as $function$
begin
 if (select count(*) from public.kamu_inventory_users) >= 20 then raise exception 'USER_LIMIT_REACHED'; end if;
 return new;
end;$function$;
create trigger trg_kamu_inventory_user_limit before insert on public.kamu_inventory_users
for each row execute function public.kamu_inventory_enforce_user_limit();

create table public.kamu_inventory_sessions (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references public.kamu_inventory_users(id) on delete cascade,
 token_hash text not null unique,
 expires_at timestamptz not null,
 created_at timestamptz not null default now()
);
create index kamu_inventory_sessions_user_idx on public.kamu_inventory_sessions(user_id);
create index kamu_inventory_sessions_exp_idx on public.kamu_inventory_sessions(expires_at);

create table public.kamu_inventory_datasets (
 id uuid primary key default gen_random_uuid(),
 owner_id uuid references public.kamu_inventory_users(id) on delete cascade,
 dataset_type text not null check (dataset_type=any(array['stock','item','bom','convert','cup_mapping','usage_source','ratio','wip_conversion'])),
 payload jsonb not null default '{}'::jsonb,
 metadata jsonb not null default '{}'::jsonb,
 updated_at timestamptz not null default now()
);
create index idx_kamu_inventory_datasets_owner_id on public.kamu_inventory_datasets(owner_id);
create unique index kamu_inventory_dataset_owner_type_uq on public.kamu_inventory_datasets(coalesce(owner_id,'00000000-0000-0000-0000-000000000000'::uuid),dataset_type);

create table public.kamu_inventory_custom_checks (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references public.kamu_inventory_users(id) on delete cascade,
 name text not null,
 rm_codes jsonb not null default '[]'::jsonb,
 updated_at timestamptz not null default now(),
 unique(user_id,name)
);

create table public.kamu_inventory_counts (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references public.kamu_inventory_users(id) on delete cascade,
 branch_code text not null,
 stock_date text not null default '',
 rm_code text not null,
 count_value numeric,
 updated_at timestamptz not null default now(),
 unique(user_id,branch_code,stock_date,rm_code)
);

create table public.kamu_inventory_logs (
 id bigserial primary key,
 user_id uuid references public.kamu_inventory_users(id) on delete set null,
 username text,
 event_type text not null,
 detail jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
create index idx_kamu_inventory_logs_user_id_created on public.kamu_inventory_logs(user_id,created_at desc);

create table public.kamu_inventory_uploads (
 id uuid primary key default gen_random_uuid(),
 owner_scope text not null,
 owner_id uuid references public.kamu_inventory_users(id) on delete cascade,
 username text,
 dataset_type text not null check (dataset_type=any(array['stock','item','bom','convert'])),
 status text not null default 'staging' check (status=any(array['staging','committed','aborted'])),
 expected_chunks integer not null check(expected_chunks>0 and expected_chunks<=500),
 expected_rows integer not null default 0 check(expected_rows>=0),
 metadata jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(),
 committed_at timestamptz
);
create index idx_kamu_inventory_uploads_owner_id on public.kamu_inventory_uploads(owner_id);
create index idx_kamu_inventory_uploads_owner_type_status on public.kamu_inventory_uploads(owner_scope,dataset_type,status,created_at desc);

create table public.kamu_inventory_dataset_chunks (
 id bigint generated by default as identity primary key,
 upload_id uuid not null references public.kamu_inventory_uploads(id) on delete cascade,
 owner_scope text not null,
 dataset_type text not null check (dataset_type=any(array['stock','item','bom','convert'])),
 chunk_index integer not null check(chunk_index>=0),
 row_count integer not null default 0 check(row_count>=0),
 payload jsonb not null default '[]'::jsonb,
 created_at timestamptz not null default now(),
 unique(upload_id,chunk_index)
);
create index idx_kamu_inventory_chunks_owner_type_upload on public.kamu_inventory_dataset_chunks(owner_scope,dataset_type,upload_id,chunk_index);

create table public.kamu_inventory_audit_history (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references public.kamu_inventory_users(id) on delete cascade,
 title text not null default '',
 branch_code text not null default '',
 branch_name text not null default '',
 item_sale_date text not null default '',
 stock_date text not null default '',
 custom_check text not null default '',
 note text not null default '',
 inspected_at timestamptz not null default now(),
 rows_count integer not null default 0,
 variance_cost numeric not null default 0,
 snapshot jsonb not null default '[]'::jsonb,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index kamu_inventory_audit_history_user_date_idx on public.kamu_inventory_audit_history(user_id,inspected_at desc);
create index kamu_inventory_audit_history_user_branch_idx on public.kamu_inventory_audit_history(user_id,branch_code,inspected_at desc);

create table public.kamu_inventory_reorder_settings (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references public.kamu_inventory_users(id) on delete cascade,
 branch_code text not null default '',
 rm_code text not null,
 lead_time_days integer not null default 0 check(lead_time_days>=0 and lead_time_days<=365),
 updated_at timestamptz not null default now(),
 unique(user_id,branch_code,rm_code)
);
create index idx_kamu_inventory_reorder_settings_user_branch on public.kamu_inventory_reorder_settings(user_id,branch_code);
create index idx_kamu_inventory_reorder_settings_rm on public.kamu_inventory_reorder_settings(rm_code);

create table public.kamu_inventory_shared_custom_checks (
 id uuid primary key default gen_random_uuid(),
 name text not null unique,
 rm_codes jsonb not null default '[]'::jsonb,
 is_active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index idx_kamu_inventory_shared_custom_checks_active_name on public.kamu_inventory_shared_custom_checks(is_active,name);

